pub const Lexeme = union(enum) {
    amp,
    arrow,
    bad_builtin,
    bral,
    brar,
    brek,
    char: u8,
    colon,
    comma,
    curl,
    curr,
    dot,
    dot2,
    els,
    eof,
    equ,
    equ2,
    ext,
    fals,
    forr,
    fun,
    hash,
    iff,
    int: u64,
    int_too_big,
    invalid,
    invalid_char,
    les,
    let,
    minus,
    mor,
    moreq,
    mut,
    name: []const u8,
    parl,
    parr,
    pipe,
    plus,
    rem,
    ret,
    semi,
    sizeof,
    slash,
    star,
    str: []const u8,
    swi,
    tild,
    tru,
    typ,
    unclosed_char,
    unclosed_str,
    undef,
    unre,
    use,
    whi,
    wild,

    pub fn describe(lexeme: @typeInfo(Lexeme).@"union".tag_type.?) []const u8 {
        return switch (lexeme) {
            .hash => "`#`",
            .bad_builtin => "#<unknown builtin>",
            .arrow => "`=>`",
            .swi => "`switch`",
            .use => "`use`",
            .typ => "`type`",
            .fals => "`false`",
            .dot2 => "`..`",
            .forr => "`for`",
            .int_too_big => "<int too big>",
            .unclosed_char => "<unclosed char>",
            .invalid_char => "<invalid char>",
            .sizeof => "`sizeof`",
            .moreq => "`>=`",
            .mor => "`>`",
            .unre => "`unreachable`",
            .brek => "`break`",
            .tru => "`true`",
            .undef => "`undefined`",
            .pipe => "`|`",
            .tild => "`~`",
            .bral => "`[`",
            .brar => "`]`",
            .mut => "`mut`",
            .wild => "`_`",
            .char => "<char>",
            .dot => "`.`",
            .els => "`else`",
            .rem => "`%`",
            .les => "`<`",
            .whi => "`while`",
            .equ2 => "`==`",
            .iff => "`if`",
            .slash => "`/`",
            .minus => "`-`",
            .plus => "`+`",
            .equ => "`=`",
            .let => "`let`",
            .comma => "`,`",
            .str => "<str>",
            .unclosed_str => "<unclosed string>",
            .name => "<name>",
            .int => "<int>",
            .ret => "`return`",
            .invalid => "<invalid>",
            .amp => "`&`",
            .star => "`*`",
            .colon => "`:`",
            .ext => "`extern`",
            .fun => "`fn`",
            .parl => "`(`",
            .parr => "`)`",
            .curl => "`{`",
            .semi => "`;`",
            .curr => "`}`",
            .eof => "<eof>",
        };
    }
};
